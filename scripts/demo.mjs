import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdir, mkdtemp, rename, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { salaryServer } from '../server/http.js';
import { openDatabase } from '../server/pay.js';
import { seed } from '../server/seed.js';

const db = openDatabase(':memory:');
seed(db);
const server = salaryServer(db, { password: 'acme-local-demo' }).listen(0, '127.0.0.1');
await once(server, 'listening');
let browser;
let recordingDir;
try {
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || undefined });
  const output = 'artifacts';
  await mkdir(output, { recursive: true });
  recordingDir = await mkdtemp(join(tmpdir(), 'salary-demo-'));
  const context = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    recordVideo: { dir: recordingDir, size: { width: 1440, height: 900 } },
  });
  const page = await context.newPage();
  const video = page.video();
  const url = 'http://127.0.0.1:' + server.address().port;
  const seconds = (count = 2) => page.waitForTimeout(count * 1000);

  await page.goto(url);
  await page.getByLabel('Username').fill('admin');
  await page.getByLabel('Password').fill('acme-local-demo');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByText('10,000 matching employees').waitFor();
  const chart = page.getByRole('region', { name: 'Annual base pay' });
  await chart.locator('.pay-values').getByText('CA$117,688.23', { exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Employees by salary band' }).waitFor();
  const departments = page.getByRole('region', { name: 'Average base pay by department' });
  assert.equal(await departments.getByRole('listitem').count(), 5);
  const euroButton = page.getByRole('button', { name: 'Show EUR salary range' });
  await euroButton.click();
  assert.equal(await euroButton.getAttribute('aria-pressed'), 'true');
  const average = chart.getByRole('button', { name: 'Average salary: EUR 75,933.65' });
  await chart.getByRole('button', { name: /^Low salary/ }).focus();
  await page.keyboard.press('Tab');
  await average.getByText('€75,933.65', { exact: true }).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Dashboard' }).getAttribute('aria-current'), 'page');
  assert.equal(await page.getByRole('row').count(), 0);
  assert.equal(await page.getByRole('searchbox').count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Clear filters' }).count(), 0);
  await seconds(3);
  await page.getByLabel('Country', { exact: true }).selectOption('India');
  await page.getByText('2,000 matching employees').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Show INR salary range' }).getAttribute('aria-pressed'), 'true');
  await page.getByLabel('Department', { exact: true }).selectOption('Engineering');
  await departments.getByRole('listitem').filter({ hasText: 'Engineering' }).waitFor();
  assert.equal(await departments.getByRole('listitem').count(), 1);
  await seconds(3);
  await page.getByRole('link', { name: 'View matching employees' }).click();
  await page.getByRole('heading', { name: 'Employee directory' }).waitFor();
  await page.getByRole('columnheader', { name: 'Employee ID' }).waitFor();
  assert.ok(page.url().endsWith('#directory'));
  assert.equal(await page.getByRole('link', { name: 'Employees' }).getAttribute('aria-current'), 'page');
  assert.equal(await page.getByLabel('Country', { exact: true }).inputValue(), 'India');
  assert.equal(await page.getByLabel('Department', { exact: true }).inputValue(), 'Engineering');
  assert.equal(await page.getByRole('heading', { name: 'Pay overview' }).count(), 0);
  await page.getByRole('button', { name: 'Edit salary', exact: false }).first().waitFor();
  await seconds();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByText('Page 1 of 400').waitFor();
  assert.equal(await page.getByRole('row').count(), 26);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByText('Page 2 of 400').waitFor();
  await seconds();
  await page.getByRole('searchbox').fill('ACME-0001');
  await page.getByRole('button', { name: 'Search' }).click();
  await page.getByText('1–1 of 1', { exact: true }).waitFor();
  await page.getByRole('link', { name: 'Dashboard' }).click();
  await page.getByText('10,000 matching employees').waitFor();
  await page.getByRole('link', { name: 'Employees', exact: true }).click();
  await page.getByText('1–1 of 1', { exact: true }).waitFor();
  await seconds();
  await page.getByRole('button', { name: /Edit salary for .* ACME-0001$/ }).click();
  const salary = page.getByLabel('Annual base salary (USD)');
  await salary.fill('72000.50');
  await seconds();
  await page.getByRole('button', { name: 'Save salary' }).click();
  await page.getByText('Salary saved.').waitFor();
  await page.getByRole('listitem').filter({ hasText: 'USD 72,000.50' }).waitFor();
  await seconds(3);
  await page.getByRole('button', { name: 'Close salary record' }).click();
  await page.getByRole('cell', { name: 'USD 72,000.50' }).waitFor();
  await seconds(3);
  await page.getByRole('button', { name: 'Log out' }).click();
  await page.getByRole('heading', { name: 'Sign in' }).waitFor();
  assert.equal((await page.request.get(url + '/api/employees')).status(), 401);
  await seconds();
  await context.close();
  const target = output + '/salary-management-demo.webm';
  await rm(target, { force: true });
  await rename(await video.path(), target);
  console.log('Browser walkthrough passed. Video saved to ' + target);
} finally {
  await browser?.close();
  if (recordingDir) await rm(recordingDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
  await new Promise(resolve => server.close(resolve));
  db.close();
}
